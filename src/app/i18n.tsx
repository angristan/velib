const dictionaries: Record<AppLocale, Messages> = { fr: french, en: english }

interface I18nContextValue {
  readonly locale: AppLocale
  readonly localeTag: "fr-FR" | "en-GB"
  readonly messages: Messages
  readonly setLocale: (locale: AppLocale) => void
}

const defaultContext: I18nContextValue = {
  locale: "fr",
  localeTag: "fr-FR",
  messages: french,
  setLocale: () => undefined,
}

const I18nContext = createContext<I18nContextValue>(defaultContext)

const initialLocale = (): AppLocale => {
  try {
    const stored = normalizeLocale(window.localStorage.getItem(STORAGE_KEY))
    if (stored !== null) return stored
  } catch {
    // Browser preferences remain available when storage is unavailable.
  }
  return normalizeLocale(window.navigator.language) ?? "fr"
}

const setMetaContent = (selector: string, content: string): void => {
  document.querySelector<HTMLMetaElement>(selector)?.setAttribute("content", content)
}

export const I18nProvider = ({ children }: { readonly children: React.ReactNode }) => {
  const [locale, setLocaleState] = useState<AppLocale>(initialLocale)
  const setLocale = useCallback((nextLocale: AppLocale) => {
    setLocaleState(nextLocale)
    try {
      window.localStorage.setItem(STORAGE_KEY, nextLocale)
    } catch {
      // The selected language still applies for the current session.
    }
  }, [])
  const messages = dictionaries[locale]

  useEffect(() => {
    document.documentElement.lang = locale
    document.title = messages.document.title
    setMetaContent('meta[name="description"]', messages.document.description)
  }, [locale, messages.document.description, messages.document.title])

  const value = useMemo<I18nContextValue>(() => ({
    locale,
    localeTag: localeTag(locale),
    messages,
    setLocale,
  }), [locale, messages, setLocale])

  return <I18nContext.Provider value={value}>{children}</I18nContext.Provider>
}

export const useI18n = (): I18nContextValue => useContext(I18nContext)
